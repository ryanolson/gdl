use super::*;

/// The Dockerfile of a segment built from local sources with no
/// `[deployment.codegen]` table, as it was before the table existed:
/// `<segment>` and `<package>` stand for its segment and package, and
/// `<toolchain>` for the toolchain step.
const PINNED: &str = "# @generated by gdl-gen; do not edit\n\
FROM --platform=$BUILDPLATFORM rust:1.93.1-slim-bookworm AS build\n\
ARG TARGETARCH\n\
RUN <toolchain>\n\
WORKDIR /app\n\
COPY . /app\n\
ENV CARGO_TARGET_DIR=/build\n\
RUN . /gdl/target.env && cargo build --locked --release --target \"$GDL_TARGET\" --manifest-path '/app/<bundle>/<segment>/Cargo.toml' && cp \"$CARGO_TARGET_DIR/$GDL_TARGET/release/<package>\" /gdl/segment\n\
FROM gcr.io/distroless/cc-debian12:nonroot\n\
ENV GLIBC_TUNABLES=glibc.malloc.hugetlb=0\n\
COPY --from=build /etc/ssl/certs/ca-certificates.crt /etc/ssl/certs/ca-certificates.crt\n\
COPY --from=build /gdl/segment /usr/local/bin/segment\n\
ENTRYPOINT [\"/usr/local/bin/segment\"]\n";

/// The Dockerfile of each segment image of `spec`, built from the copy's
/// sources for the clusters of `fleet`, by its package, with the
/// toolchain step as `<toolchain>`.
fn dockerfiles(spec: &gdl_gen::Spec, fleet: &gdl_model::Fleet) -> BTreeMap<String, String> {
    let mut docker = Fake::default();
    gdl_gen::images(
        spec,
        fleet,
        &gdl_gen::Dgds::default(),
        &target(),
        false,
        gdl_gen::Sources::Local,
        &mut docker,
    )
    .expect("images");
    docker
        .contexts
        .iter()
        .filter_map(|(reference, context)| {
            let (_, repository, _) = super::super::split(reference);
            (repository != "api-hub").then(|| {
                let dockerfile = &context[Path::new("Dockerfile")];
                let start = dockerfile.find("RUN set -eu;").expect("a toolchain step") + 4;
                let end = start + dockerfile[start..].find("\nWORKDIR ").expect("its end");
                (
                    repository.to_string(),
                    format!("{}<toolchain>{}", &dockerfile[..start], &dockerfile[end..]),
                )
            })
        })
        .collect()
}

/// With local sources too, a spec with no table builds each segment as
/// before the table existed, and a table for arm64 leaves the amd64
/// images' Dockerfiles as they were and reaches the arm64 ones. It
/// builds the images three times from one copy, and each build settles
/// the segments' locks, so it takes about 20 to 30 s on a busy host.
#[test]
fn local_images_take_codegen_for_their_own_architecture_only() {
    let copy = Copy::new();
    let plain = copy.spec();
    let dir = copy.path().join("examples/api");
    let text = std::fs::read_to_string(dir.join("gdl.toml"))
        .expect("the spec")
        .replace(SEGMENTS, SPLIT);
    let graph = std::fs::read_to_string(dir.join("api.gdl")).expect("the graph");
    let tabled = gdl_gen::Spec::from_text(
        &format!("{text}\n[deployment.codegen.arm64]\ntarget_features = [\"+lse\"]\n"),
        &graph,
        &dir,
    )
    .expect("a spec");
    let amd64 = fleet();
    // The same fleet, its one cluster of arm64.
    let arm64 = gdl_model::Fleet::from_toml(
        "[fleet]\nname = \"api\"\n\
         [cluster.use1]\ncontext = \"kind-use1\"\nnamespace = \"gdl-api\"\nregion = \"us-east-1\"\n\
         registry = \"registry.example/gdl\"\nplatform = \"linux/arm64\"\n\
         [class.global]\nready = { front = 1 }\n[class.model_x]\nready = { engine = 1 }\n\
         [pool.global-us]\nclass = \"global\"\ncluster = \"use1\"\n\
         [pool.model-x-us]\nclass = \"model_x\"\ncluster = \"use1\"\nhome = \"global-us\"\n",
    )
    .expect("a fleet");
    let before = dockerfiles(&plain, &amd64);
    assert_eq!(before.len(), 2, "{before:?}");
    for (package, dockerfile) in &before {
        let segment = package.strip_prefix("api-").expect("a segment");
        let bundle = dockerfile
            .split("--manifest-path '/app/")
            .nth(1)
            .and_then(|rest| rest.split(&format!("/{segment}/Cargo.toml")).next())
            .expect("the bundle's place");
        let pinned = PINNED
            .replace("<bundle>", bundle)
            .replace("<segment>", segment)
            .replace("<package>", package);
        assert_eq!(dockerfile, &pinned, "{package}");
    }
    assert_eq!(dockerfiles(&tabled, &amd64), before);
    for (package, dockerfile) in dockerfiles(&tabled, &arm64) {
        let cargo = "export RUSTFLAGS=\"-Ctarget-feature=+lse\" && \\\n    cargo build --locked ";
        assert!(dockerfile.contains(cargo), "{package}:\n{dockerfile}");
        assert!(
            dockerfile.contains("{ [ \"$TARGETARCH\" = arm64 ] || "),
            "{package}:\n{dockerfile}"
        );
    }
}
